import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";

// The browser's bootstrap module is content-hashed, so the server can only learn
// its name from the build. Vite writes it to dist/static/.vite/manifest.json —
// but a deploy has to actually SHIP that file to the function, and Vercel copies
// neither the .vite/ dot-directory (its includeFiles glob skips it) nor a JSON
// import (its tracer doesn't follow one). Either way the function crashes on its
// first request.
//
// A .js import IS traced. So write the one value the server needs out as a
// module, and let the bundler follow it like any other import.

const manifest = JSON.parse(
  readFileSync(resolve("dist", "static", ".vite", "manifest.json"), "utf8"),
);
// The static build keys the browser bootstrap under the HTML input — that entry
// is the bundled src/client.tsx, i.e. startClient.
const clientEntry = manifest["index.html"]?.file;
if (!clientEntry) throw new Error("[emit-client-entry] no index.html entry in the client manifest");

const out = resolve("dist", "client-entry.mjs");
writeFileSync(out, `// Generated by scripts/emit-client-entry.mjs — do not edit.\nexport const clientEntry = ${JSON.stringify(clientEntry)};\n`);
console.log(`[emit-client-entry] ${clientEntry} → dist/client-entry.mjs`);

// The build copies the client islands' vprs chunks into
// dist/client/node_modules/<pkg>/… but NOT the package's own package.json. Those
// chunks are ESM (e.g. `export { Link }`); with no local "type":"module" their
// format is decided by the nearest parent package.json. Running from the project
// root that's ours (type:module) and it works — but a serverless function ships
// only dist/** (see includeFiles), so the root package.json isn't co-located and
// Node reads the chunks as CJS. Their named exports then vanish, the client
// island fails to instantiate during SSR, and the whole document render degrades
// to a blank shell with no #root. Stamp a minimal package.json into each vendored
// package so the chunks are unambiguously ESM wherever the function runs.
function stampEsm(nodeModulesDir) {
  if (!existsSync(nodeModulesDir)) return;
  for (const name of readdirSync(nodeModulesDir)) {
    if (name.startsWith(".")) continue;
    const entry = resolve(nodeModulesDir, name);
    if (!statSync(entry).isDirectory()) continue;
    // Scoped packages (@scope/name) nest one level deeper.
    const pkgDirs = name.startsWith("@")
      ? readdirSync(entry).map((n) => resolve(entry, n))
      : [entry];
    for (const dir of pkgDirs) {
      const pkgJson = resolve(dir, "package.json");
      if (existsSync(pkgJson)) continue;
      writeFileSync(pkgJson, `${JSON.stringify({ type: "module" })}\n`);
      console.log(`[emit-client-entry] stamped ESM ${pkgJson.slice(resolve("dist").length + 1)}`);
    }
  }
}
stampEsm(resolve("dist", "client", "node_modules"));
