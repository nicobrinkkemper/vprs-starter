import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// The browser's bootstrap module is content-hashed, so the server can only learn
// its name from the build. Vite writes it to dist/static/.vite/manifest.json —
// but a deploy has to actually SHIP that file to the function, and Vercel copies
// neither the .vite/ dot-directory (its includeFiles glob skips it) nor a JSON
// import (its tracer doesn't follow one). Either way the function crashes on its
// first request.
//
// A .js import IS traced. So write the one value the server needs out as a
// module, and let the bundler follow it like any other import.

const manifest = JSON.parse(
  readFileSync(resolve("dist", "static", ".vite", "manifest.json"), "utf8"),
);
// The static build keys the browser bootstrap under the HTML input — that entry
// is the bundled src/client.tsx, i.e. startClient.
const clientEntry = manifest["index.html"]?.file;
if (!clientEntry) throw new Error("[emit-client-entry] no index.html entry in the client manifest");

const out = resolve("dist", "client-entry.mjs");
writeFileSync(out, `// Generated by scripts/emit-client-entry.mjs — do not edit.\nexport const clientEntry = ${JSON.stringify(clientEntry)};\n`);
console.log(`[emit-client-entry] ${clientEntry} → dist/client-entry.mjs`);
